export interface StageVersion {
  id: string;
  timestamp: number;
  output: string;
  input: string;
  questions: string[];
  coherenceScore: number;
  searchEntryPointHtml?: string;
}

export interface StageData {
  input: string;
  output: string;
  files: FileContext[];
  urls: string[]; // New: Stage-specific reference URLs
  formatReference?: FileContext; // Optional template/format file
  status: 'pending' | 'completed' | 'error';
  questions: string[]; // Questions generated by AI
  answers: Record<string, string>; // User answers to those questions
  thinkingTemperature?: number; // Saved temperature for this stage
  thinkingTopP?: number; // Saved TopP for this stage
  groundingSources?: GroundingSource[];
  searchEntryPointHtml?: string; // HTML snippet showing search queries
  versions: StageVersion[];
  coherenceScore: number;
  estimationSheetData?: any; // JSON string or object for spreadsheet state
  enabledNamespaces?: VectorNamespace[]; // RAG: Active Pinecone namespaces for this stage
  isFigmaEnabled?: boolean; // Toggle state
  figmaConfig?: { accessToken: string; fileKey: string }; // Connection details
  figmaData?: any; // The raw or summarized Figma response captured for this stage

  // Notion Integration
  isNotionEnabled?: boolean;
  notionConfig?: NotionConfig;
  notionData?: any; // The captured Markdown content from Notion

  // Confluence Integration
  isConfluenceEnabled?: boolean;
  confluenceConfig?: ConfluenceConfig;

  // Shadow Competitor Simulation Engine
  shadowCompetitorAnalysis?: {
    status: 'idle' | 'running' | 'paused' | 'completed' | 'error';
    competitors: Array<{
      name: string;
      region: string;
      regulatoryBody: string;
      confidence: string;
    }>;
    progress: {
      phase: 1 | 2 | 3;
      overall: number;
      perCompetitor: Record<string, number>;
    };
    results?: {
      dna: any[];
      warGaming: any[];
      moat: any;
      citations: any[];
      fullReport: string;
    };
    lastRun?: number;
  };
}


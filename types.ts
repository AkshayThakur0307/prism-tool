
export enum DiscoveryStage {
  DOMAIN = 'DOMAIN',
  BOD = 'BOD',
  KPI = 'KPI',
  EPICS = 'EPICS'
}

export interface FileContext {
  name: string;
  content: string; // Base64 for images, text for others
  mimeType: string;
  size: number;
}

export interface GroundingSource {
  title: string;
  uri: string;
}

export interface ProjectMetadata {
  companyName: string;
  missionStatement: string;
  targetVertical: string;
  geography: string;
  tam: string;
  revenueModel: string;
  websiteUrls: string;
  keyCompetitors: string;
}

export interface StageVersion {
  id: string;
  timestamp: number;
  output: string;
  input: string;
  questions: string[];
  coherenceScore: number;
  searchEntryPointHtml?: string;
}

export interface StageData {
  input: string;
  output: string;
  files: FileContext[];
  urls: string[]; // New: Stage-specific reference URLs
  formatReference?: FileContext; // Optional template/format file
  status: 'pending' | 'completed' | 'error';
  questions: string[]; // Questions generated by AI
  answers: Record<string, string>; // User answers to those questions
  groundingSources?: GroundingSource[];
  searchEntryPointHtml?: string; // HTML snippet showing search queries
  versions: StageVersion[];
  coherenceScore: number;
  estimationSheetData?: any; // JSON string or object for spreadsheet state
}

export interface ProjectSettings {
  isThinkingEnabled: boolean;
  thinkingTemperature?: number; // Optional 0.0 - 1.0
  thinkingTopP?: number; // Optional 0.0 - 1.0
  isSearchEnabled: boolean;
}

export interface AppState {
  currentStage: DiscoveryStage;
  projectMetadata: ProjectMetadata;
  settings: ProjectSettings;
  stages: Record<DiscoveryStage, StageData>;
}

export interface Project extends AppState {
  id: string;
  userId: string;
  userName?: string;
  name: string;
  createdAt: number;
  updatedAt: number;
  sharedWith?: Record<string, {
    email: string;
    role: 'viewer';
    sharedAt: number;
    sharedBy: string;
  }>;
}

export interface VoiceState {
  isActive: boolean;
  isListening: boolean;
  isSpeaking: boolean;
  transcript: string;
}

export type UserRole = 'viewer' | 'standard' | 'pro' | 'admin';

export interface UserProfile {
  uid: string;
  email: string;
  displayName?: string;
  role: UserRole;
  createdAt: number;
}
